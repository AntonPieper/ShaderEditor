package de.markusfisch.android.shadereditor.opengl;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertNull;

import org.junit.Test;

import java.util.List;

import de.markusfisch.android.shadereditor.project.ProjectDiagnostic;
import de.markusfisch.android.shadereditor.project.ProjectDiagnostic.Severity;
import de.markusfisch.android.shadereditor.project.ProjectPath;
import de.markusfisch.android.shadereditor.project.SourceLocation;
import de.markusfisch.android.shadereditor.project.SourceMap;

public class DriverLogTest {
	private static final String DRIVER_LINE =
			"ERROR: 0:12: 'foo' : undeclared identifier";

	@Test
	public void parseExtractsLineAndMessage() {
		ProjectDiagnostic error = single(DRIVER_LINE,
				null);
		assertEquals(Severity.ERROR, error.severity());
		assertNull(error.file());
		assertEquals(12, error.line());
		assertEquals("'foo' : undeclared identifier", error.message());
		assertEquals(DRIVER_LINE, error.raw());
		assertEquals("12: 'foo' : undeclared identifier", error.toString());
	}

	@Test
	public void warningKeepsItsSeverity() {
		ProjectDiagnostic warning = single(
				"WARNING: 0:3: 'x' : variable is unused",
				null);
		assertEquals(Severity.WARNING, warning.severity());
		assertEquals(3, warning.line());
		assertEquals("'x' : variable is unused", warning.message());
	}

	@Test
	public void unfamiliarFormatIsKeptRaw() {
		String mesa = "0:12(5): error: `foo' undeclared";
		ProjectDiagnostic error = single(mesa, null);
		assertEquals(Severity.ERROR, error.severity());
		assertNull(error.file());
		assertEquals(0, error.line());
		assertEquals(mesa, error.message());
		assertEquals(mesa, error.raw());
		assertEquals(mesa, error.toString());
	}

	@Test
	public void parseKeepsEveryLine() {
		List<ProjectDiagnostic> errors = DriverLog.parse(
				DRIVER_LINE + "\nERROR: 1 compilation errors.",
				null);
		assertEquals(2, errors.size());
		assertEquals(12, errors.get(0).line());
		assertEquals(0, errors.get(1).line());
		assertEquals("ERROR: 1 compilation errors.", errors.get(1).message());
	}

	@Test
	public void sourceMapNamesTheNestedInclude() {
		// The engine adds one line on top of the assembled source.
		SourceMap mapping = nestedIncludeMap().insertGenerated(0, 1);
		String log = "ERROR: 0:4: 'noise' : no matching overloaded function";
		ProjectDiagnostic error = single(log, mapping);
		assertEquals(path("lib/b.glsl"), error.file());
		assertEquals(2, error.line());
		assertEquals("'noise' : no matching overloaded function",
				error.message());
		assertEquals(log, error.raw());
		assertEquals("lib/b.glsl:2: 'noise' : no matching overloaded function",
				error.toString());
	}

	@Test
	public void unmappableLinesAreKeptRaw() {
		SourceMap mapping = nestedIncludeMap().insertGenerated(0, 1);
		for (String log : List.of(
				"ERROR: 0:1: in an engine line",
				"ERROR: 0:8: generated by the assembly",
				"ERROR: 0:40: past the end")) {
			ProjectDiagnostic error = single(log, mapping);
			assertNull(error.file());
			assertEquals(0, error.line());
			assertEquals(log, error.message());
			assertEquals(log, error.raw());
		}
	}

	private static SourceMap nestedIncludeMap() {
		SourceLocation includeA = new SourceLocation(path("main.frag"), 2, null);
		SourceLocation includeB = new SourceLocation(path("lib/a.glsl"), 1,
				includeA);
		return new SourceMap(List.of(
				new SourceLocation(path("main.frag"), 1, null),
				new SourceLocation(path("lib/b.glsl"), 1, includeB),
				new SourceLocation(path("lib/b.glsl"), 2, includeB),
				new SourceLocation(path("lib/a.glsl"), 2, includeA),
				new SourceLocation(path("main.frag"), 3, null),
				new SourceLocation(path("main.frag"), 4, null),
				SourceLocation.GENERATED));
	}

	private static ProjectDiagnostic single(String log,
			SourceMap mapping) {
		List<ProjectDiagnostic> diagnostics = DriverLog.parse(log, mapping);
		assertEquals(1, diagnostics.size());
		return diagnostics.get(0);
	}

	private static ProjectPath path(String path) {
		return ProjectPath.parse(path).value();
	}
}
